CREATE TABLE event (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_token     VARCHAR(32)   NOT NULL UNIQUE,
    couple_names   VARCHAR(200)  NOT NULL,
    event_type     VARCHAR(30)   NOT NULL,
    starts_at      TIMESTAMP     NOT NULL,
    venue          VARCHAR(300)  NOT NULL,
    maps_url       VARCHAR(1000),
    template       VARCHAR(30)   NOT NULL,
    message_en     VARCHAR(2000) NOT NULL,
    message_ml     VARCHAR(2000) NOT NULL,
    created_at     TIMESTAMP     NOT NULL,
    updated_at     TIMESTAMP     NOT NULL
);

CREATE TABLE event_photo (
    event_id     BIGINT       PRIMARY KEY REFERENCES event (id) ON DELETE CASCADE,
    content_type VARCHAR(50)  NOT NULL,
    data         BYTEA        NOT NULL
);

CREATE TABLE guest (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     BIGINT       NOT NULL REFERENCES event (id) ON DELETE CASCADE,
    token        VARCHAR(32)  NOT NULL UNIQUE,
    name         VARCHAR(200) NOT NULL,
    phone        VARCHAR(20)  NOT NULL,
    sent_at      TIMESTAMP,
    rsvp_status  VARCHAR(20)  NOT NULL,
    headcount    INTEGER,
    responded_at TIMESTAMP,
    created_at   TIMESTAMP    NOT NULL,
    CONSTRAINT uq_guest_event_phone UNIQUE (event_id, phone)
);

CREATE INDEX idx_guest_event ON guest (event_id, id);
